"""Generates src/assets/styles/palettes.css and src/context/palettes.ts from palettes.txt.

Run from anywhere: python scripts/palettes/generate.py
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).parent
FRONTEND = HERE.parent.parent / "src"

KEYS = ("page surface surface2 input border borderStrong text text2 text3 primary primaryHover onPrimary accent "
        "accentText accentSoft focus danger dangerText dangerSoft success successText successSoft warn warnText "
        "warnSoft info infoText infoSoft viewer loginBgFrom loginBgTo loginLine loginHighlight").split()

CSS_NAMES = {
    "page": "--c-page", "surface": "--c-surface", "surface2": "--c-surface-2", "input": "--c-input",
    "border": "--c-border", "borderStrong": "--c-border-strong", "text": "--c-text", "text2": "--c-text-2",
    "text3": "--c-text-3", "primary": "--c-primary", "primaryHover": "--c-primary-hover",
    "onPrimary": "--c-on-primary", "accent": "--c-accent", "accentText": "--c-accent-text",
    "accentSoft": "--c-accent-soft", "focus": "--c-focus", "danger": "--c-danger", "dangerText": "--c-danger-text",
    "dangerSoft": "--c-danger-soft", "success": "--c-success", "successText": "--c-success-text",
    "successSoft": "--c-success-soft", "warn": "--c-warn", "warnText": "--c-warn-text", "warnSoft": "--c-warn-soft",
    "info": "--c-info", "infoText": "--c-info-text", "infoSoft": "--c-info-soft", "viewer": "--c-viewer",
    "loginBgFrom": "--login-bg-from", "loginBgTo": "--login-bg-to", "loginLine": "--login-line",
    "loginHighlight": "--login-highlight",
}

GROUPS = {"Spokojne": "classic", "Odważne": "bold"}


def parse(path):
    palettes = []
    current = None
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line.startswith("PALETA "):
            parts = [p.strip() for p in line[len("PALETA "):].split("|")]
            pid, name, group = parts[0], parts[1], parts[2].replace("grupa ", "")
            fields = {}
            for part in parts[3:]:
                if part.startswith(("sans:", "mono:", "fonty:")):
                    key, _, value = part.partition(":")
                else:
                    key, _, value = part.partition(" ")
                fields[key.strip()] = value.strip()
            radius = fields["radius"].split()
            current = {
                "id": pid, "name": name.replace(" (obecna)", ""), "group": GROUPS[group],
                "sans": fields["sans"], "mono": fields["mono"],
                "fontHref": f"https://fonts.googleapis.com/css2?{fields['fonty']}&display=swap",
                "radius": radius, "border": fields["border"],
            }
            palettes.append(current)
        elif line.startswith(("LIGHT:", "DARK:")):
            mode, _, values = line.partition(":")
            tokens = re.findall(r"rgba\([^)]*\)|\d+,\d+,\d+|#[0-9a-fA-F]{6}", values)
            assert len(tokens) == len(KEYS), (current["id"], mode, len(tokens))
            current[mode.lower()] = dict(zip(KEYS, tokens))
    return palettes


def ring(focus, accent):
    """3 px focus ring colour: translucent version of the focus colour."""
    if focus.startswith("rgba"):
        return focus
    r, g, b = (int(focus[i:i + 2], 16) for i in (1, 3, 5))
    return f"rgba({r}, {g}, {b}, 0.28)"


def outline(focus, accent):
    """1–2 px focus outline: the focus colour when opaque, else the accent."""
    return accent if focus.startswith("rgba") else focus


def block(selector, values):
    return "\n".join([f"{selector} {{"] + [f"  {k}: {v};" for k, v in values.items()] + ["}", ""])


def theme_values(t):
    values = {}
    for key in KEYS:
        value = t[key]
        if key == "loginLine":
            value = value.replace(",", ", ")
        values[CSS_NAMES[key]] = value
    values["--c-focus-ring"] = ring(t["focus"], t["accent"])
    values["--c-focus-outline"] = outline(t["focus"], t["accent"])
    return values


palettes = parse(HERE / "palettes.txt")
css = ["/* Generated by scripts/palettes/generate.py from palettes.txt; switched via data-palette on <html>.", "   Derived tokens are computed from these in theme.css. */", ""]
for p in palettes:
    shape = {
        "--font-sans": p["sans"], "--font-mono": p["mono"],
        "--radius-sm": p["radius"][0], "--radius-md": p["radius"][1], "--radius-lg": p["radius"][2],
        "--border-width": p["border"],
    }
    css.append(block(f":root[data-palette='{p['id']}']", {**shape, **theme_values(p["light"])}))
    css.append(block(f":root[data-palette='{p['id']}'][data-theme='dark']", theme_values(p["dark"])))
(FRONTEND / "assets/styles/palettes.css").write_text("\n".join(css), encoding="utf-8")

items = []
for p in palettes:
    swatch = lambda t: [t["page"], t["surface"], t["primary"], t["accent"]]
    items.append({"id": p["id"], "name": p["name"], "group": p["group"], "fontHref": p["fontHref"],
                  "light": swatch(p["light"]), "dark": swatch(p["dark"])})


def ts_obj(item):
    text = json.dumps(item, ensure_ascii=False)
    for key in ("id", "name", "group", "fontHref", "light", "dark"):
        text = text.replace(f'"{key}"', key)
    return "  " + text.replace('"', "'")


ts = f"""// Colour palettes the team can switch between; values live in assets/styles/palettes.css (generated).
export type PaletteGroup = 'classic' | 'bold';

export interface PaletteOption {{
  id: string;
  name: string;
  group: PaletteGroup;
  /** Google Fonts stylesheet with the palette's fonts; injected only while the palette is active. */
  fontHref?: string;
  /** Swatches for the picker: page, surface, primary, accent. */
  light: [string, string, string, string];
  dark: [string, string, string, string];
}}

/** New users start on the recommended palette; a remembered choice wins. */
export const DEFAULT_PALETTE = 'papier-dab';

export const PALETTES: PaletteOption[] = [
{",\n".join(ts_obj(i) for i in items)},
];
"""
(FRONTEND / "context/palettes.ts").write_text(ts, encoding="utf-8")
print("ok", [p["id"] for p in palettes])
